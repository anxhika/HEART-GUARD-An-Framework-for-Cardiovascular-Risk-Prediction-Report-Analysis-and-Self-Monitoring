    def validate_report(
        self,
        parameters: List[Dict[str, Any]],
        raw_text: str = "",
        patient_context: Optional[Dict[str, Any]] = None
    ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]], bool, bool]:
        """
        Validates a list of extracted parameters and the raw text against clinical guidelines.
        Returns:
            (validated_parameters, clinical_flags, has_abnormal, has_critical)
        """
        validated_params = []
        flags = []
        has_abnormal = False
        has_critical = False

        for param in parameters:
            p_name = param.get('parameter_name', '')
            val = param.get('value', '')
            num_val = param.get('numeric_value')
            unit = param.get('unit', '')
            status = param.get('status', 'unknown')
            flag_str = param.get('flag', '')
            ref_range = param.get('reference_range', '')
            evidence = param.get('evidence', '')
            significance = param.get('clinical_significance', '')

            # Match to known quantitative rule
            rule_key, rule_def = self._match_rule(p_name)

            if rule_def and num_val is not None:
                # Perform range evaluation
                eval_status, eval_flag, eval_sig, is_crit = self._evaluate_numeric(num_val, rule_def)
                status = eval_status
                flag_str = eval_flag
                if not significance:
                    significance = eval_sig
                if not ref_range:
                    ref_range = f"{rule_def.get('min_normal', 0)}-{rule_def.get('max_normal', '')} {rule_def.get('unit', '')}".strip()

                if eval_status in ['abnormal', 'critical']:
                    has_abnormal = True
                    flag_item = {
                        'severity': 'critical' if is_crit else 'warning',
                        'parameter': rule_def['label'],
                        'value': f"{num_val} {unit or rule_def['unit']}",
                        'reference': ref_range,
                        'message': eval_sig,
                        'guideline': rule_def.get('guideline', '')
                    }
                    flags.append(flag_item)
                    if is_crit:
                        has_critical = True
            elif status in ['abnormal', 'critical']:
                has_abnormal = True
                is_crit = (status == 'critical')
                if is_crit:
                    has_critical = True
                flags.append({
                    'severity': 'critical' if is_crit else 'warning',
                    'parameter': p_name,
                    'value': val,
                    'reference': ref_range or 'Clinical normal',
                    'message': significance or f"Parameter flagged as {status}",
                    'guideline': 'Report documentation review'
                })

            validated_params.append({
                'parameter_name': p_name,
                'value': str(val),
                'numeric_value': num_val,
                'unit': unit or (rule_def.get('unit', '') if rule_def else ''),
                'reference_range': ref_range,
                'status': status,
                'flag': flag_str,
                'evidence': evidence,
                'clinical_significance': significance
            })

        # Check qualitative text patterns
        import re
        text_lower = raw_text.lower()
        for pattern, severity, msg in self.QUALITATIVE_PATTERNS:
            if re.search(pattern, text_lower):
                has_abnormal = True
                is_crit = (severity == 'CRITICAL')
                if is_crit:
                    has_critical = True
                # Check for duplicate message
                if not any(f.get('message') == msg for f in flags):
                    flags.append({
                        'severity': severity.lower(),
                        'parameter': 'Impression / Narrative Finding',
                        'value': 'Identified in report text',
                        'reference': 'Normal physiological baseline',
                        'message': msg,
                        'guideline': 'Review clinical narrative'
                    })

        return validated_params, flags, has_abnormal, has_critical

    def _match_rule(self, parameter_name: str) -> Tuple[Optional[str], Optional[Dict[str, Any]]]:
        p_clean = parameter_name.lower().strip()
        for rule_key, rule_def in self.RULES.items():
            for alias in rule_def['aliases']:
                if alias in p_clean:
                    return rule_key, rule_def
        return None, None

    def _evaluate_numeric(self, val: float, rule: Dict[str, Any]) -> Tuple[str, str, str, bool]:
        min_n = rule.get('min_normal')
        max_n = rule.get('max_normal')
        min_c = rule.get('min_critical')
        max_c = rule.get('max_critical')
        label = rule.get('label', 'Parameter')
        unit = rule.get('unit', '')

        # Check critical
        if min_c is not None and val < min_c:
            return 'critical', 'CRITICAL_LOW', f"{label} is critically low ({val} {unit}). Immediate clinical review recommended.", True
        if max_c is not None and val >= max_c:
            return 'critical', 'CRITICAL_HIGH', f"{label} is critically elevated ({val} {unit}). Immediate clinical review recommended.", True

        # Check abnormal
        if min_n is not None and val < min_n:
            return 'abnormal', 'LOW', f"{label} is below the standard reference range ({val} {unit}).", False
        if max_n is not None and val > max_n:
            return 'abnormal', 'HIGH', f"{label} is elevated above the standard reference range ({val} {unit}).", False

        return 'normal', 'NORMAL', f"{label} is within the expected physiological range ({val} {unit}).", False
